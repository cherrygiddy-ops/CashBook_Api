
CREATE TABLE cashbook_members (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                  cashbook_id BIGINT NOT NULL,
                                  user_id BIGINT NOT NULL,

                                  member_role VARCHAR(20) NOT NULL,

                                  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
                                  updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,

                                  CONSTRAINT fk_cashbook_members_cashbook
                                      FOREIGN KEY (cashbook_id)
                                          REFERENCES cashbooks(id)
                                          ON DELETE CASCADE,

                                  CONSTRAINT fk_cashbook_members_user
                                      FOREIGN KEY (user_id)
                                          REFERENCES cashbook_user(id)
                                          ON DELETE CASCADE,

                                  CONSTRAINT uk_cashbook_member
                                      UNIQUE (cashbook_id, user_id),

                                  CONSTRAINT chk_cashbook_member_role
                                      CHECK (member_role IN ('ACCOUNTANT', 'VIEWER'))
);

CREATE INDEX idx_cashbook_members_cashbook
    ON cashbook_members(cashbook_id);

CREATE INDEX idx_cashbook_members_user
    ON cashbook_members(user_id);
